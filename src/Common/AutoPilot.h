//
//  Common/AutoPilot.h —— AI 自动调参（闭环控制器）
//
//  解决什么问题：
//    浮窗已经有 11 个滑块，但没人知道该拨到哪。倍率调高怕风控，调低没收益；
//    观看时长、发奖冷却、点击延迟互相牵扯。手动试一轮要几十条广告。
//
//  这里做两件事：
//
//  1) 「一个滑块管全局」—— 激进程度 a ∈ [0,1]
//     一条曲线同时推 6 个参数：
//       · 收益倍率     1.2 → 8.0
//       · 发奖冷却     120 → 8 秒
//       · 最短观看     28  → 0 秒
//       · 最长观看     60  → 0.5 秒
//       · 点击延迟下   1200 → 200 毫秒
//       · 点击延迟上   3500 → 900 毫秒
//     拨到 0.3 是保守跑法，0.9 是猛跑，不用自己算组合。
//
//  2) 「闭环修正」—— 每 15 秒采样一次发奖速率
//     实测 < 目标×0.8  → 激进程度 +0.08（收紧延迟、提倍率）
//     实测 > 目标×1.3  → 激进程度 −0.08（放松节奏，避开风控规律）
//     落在中间          → 保持不动
//
//  参数存在哪：
//    ★ 唯一真相是 CKParam 表（也就是浮窗那两个滑块）。
//      本模块不另存一份状态，只读 CKParamGet / 写 CKParamSet。
//      所以 AI 调完之后，浮窗滑块会跟着动，用户能看见它做了什么；
//      用户手动拖，AI 下一拍就读到新值，不会互相覆盖。
//
//  安全边界（重要）：
//    · 所有写入都过 CKParamSet，会被夹到滑块范围内，写不出越界值
//    · 闭环单次调整幅度限制在 ±8%，且每 20 秒最多动一次，防震荡
//    · 连续 3 次调整误差没缩小 → 自动冻结，打日志，参数定住
//    · 冻结后不会自己恢复，要用户点「恢复自动」或手动拖滑块
//    · 一条 hook 都没装上时不调参（调了没意义），浮窗上写明原因
//
//  可选远程大脑（默认关）：
//    ENABLE_AUTOPILOT_REMOTE=1 且填 AUTOPILOT_ENDPOINT，
//    会 POST 一份统计，期望返回 {"params":{"ecpm.multiplier":4.2,...}}
//    返回值同样过幅度限制 + 范围夹取，远程改不坏本地配置。
//

#ifndef CK_AUTOPILOT_H
#define CK_AUTOPILOT_H

#import <Foundation/Foundation.h>

// 启动 / 停止（启动是幂等的，重复调用无副作用）
void CKAPStart(void);
void CKAPStop(void);
BOOL CKAPRunning(void);

// 手动设激进程度并一次性铺开 6 个参数（不受 8% 幅度限制）
// 浮窗拖「AI 激进程度」滑块时调这里
void CKAPApplyCurveNow(double a);

// 立即评估一次（浮窗「立即调整」按钮）
void CKAPTickNow(void);

// 解除冻结，恢复自动
void CKAPResume(void);

// 浮窗状态行，例如：
//   「AI 激进0.55 目标3.0 实测2.4/分 倍率4.2 调5次」
NSString *CKAPStatusLine(void);

// 最后一次决策原因（给日志 / 浮窗第二行）
NSString *CKAPLastReason(void);

// 远程配置应用（不联网，纯解析 + 夹取，便于离线测试）
// 返回成功应用的参数个数；失败返回 -1
NSInteger CKAPApplyRemoteJSON(NSData *json);

#endif
